def _validate(df: pd.DataFrame) -> pd.DataFrame:
    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        raise ValueError(f"Dataset is missing required columns: {missing}")
    if "label" not in df.columns:
        df["label"] = None
    if "account_age_days" not in df.columns:
        df["account_age_days"] = None
    return df


def load_reviews() -> pd.DataFrame:
    """Single entry point used by every other script. Swap the function
    called here once you have real data."""
    return load_sample_data()


if __name__ == "__main__":
    df = load_reviews()
    print(f"Loaded {len(df)} reviews, {df['reviewer_id'].nunique()} reviewers, "
          f"{df['product_id'].nunique()} products")
    print(df.dtypes)
