import pandas as pd
from pathlib import Path

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
REQUIRED_COLUMNS = [
    "review_id", "reviewer_id", "product_id", "rating",
    "review_text", "date", "verified_purchase",
]


def load_sample_data() -> pd.DataFrame:
    """Loads the synthetic dataset generated by generate_sample_data.py."""
    path = DATA_DIR / "raw" / "reviews_sample.csv"
    if not path.exists():
        raise FileNotFoundError(
            f"{path} not found. Run `python src/generate_sample_data.py` first."
        )
    df = pd.read_csv(path, parse_dates=["date"])
    return _validate(df)


